/**
 * Generates per-platform fallback @font-face declarations with real metric overrides.
 *
 * WHY THIS EXISTS
 * next/font/local's `adjustFontFallback` only accepts 'Arial' | 'Times New Roman',
 * and the face it generates is `src: local("Arial")`. Neither font exists on Android
 * — the exact device CLAUDE.md's perf budget is measured on — so on that device the
 * generated face never resolves, the overrides never apply, and the swap shifts
 * layout with the full CLS the overrides were meant to prevent. It fails silently and
 * only on the device that matters.
 *
 * So `adjustFontFallback` is off and these replace it: one face per platform, each
 * with size-adjust / ascent-override / descent-override / line-gap-override computed
 * against *that* system font. The font-family stack then lists them in order, and
 * each platform resolves the first one it actually has.
 *
 * WHERE THE NUMBERS COME FROM
 * Nothing here is hand-measured or estimated. Webfont metrics are read from the real
 * subset woff2 by @capsizecss/unpack; system font metrics are the published tables in
 * @capsizecss/metrics. The ratio formula is Capsize's own `createFontStack`:
 *
 *   sizeAdjust       = (webfont.xWidthAvg / webfont.upm) / (fallback.xWidthAvg / fallback.upm)
 *   adjustedEmSquare = webfont.upm * sizeAdjust
 *   ascentOverride   = webfont.ascent      / adjustedEmSquare
 *   descentOverride  = |webfont.descent|   / adjustedEmSquare
 *   lineGapOverride  = webfont.lineGap     / adjustedEmSquare
 *
 * xWidthAvg rather than xHeight is deliberate and is what Capsize switched to: average
 * character width predicts line-break behaviour, which is what actually causes reflow.
 *
 * Run: node scripts/generate-font-fallbacks.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs'

import { fromBuffer } from '@capsizecss/unpack'

const OUT = 'src/app/font-fallbacks.generated.css'

/**
 * Each webfont, and the system fonts to match it against IN STACK ORDER.
 *
 * Android first in every case: it is the budget device, and it is the platform whose
 * system fonts Next cannot target at all. Desktop and iOS pick up the second entry.
 */
const STACKS = [
  {
    file: 'src/fonts/redaction-regular.woff2',
    label: 'Redaction',
    fallbacks: [
      {
        family: 'Redaction Fallback Noto',
        local: 'Noto Serif',
        metrics: 'notoSerif',
        platform: 'Android',
      },
      {
        family: 'Redaction Fallback Times',
        local: 'Times New Roman',
        metrics: 'timesNewRoman',
        platform: 'Windows / macOS / iOS',
      },
    ],
  },
  {
    file: 'src/fonts/redaction20-bold.woff2',
    label: 'Redaction 20 (degraded)',
    fallbacks: [
      {
        family: 'Redaction Degraded Fallback Noto',
        local: 'Noto Serif',
        metrics: 'notoSerif',
        platform: 'Android',
      },
      {
        family: 'Redaction Degraded Fallback Times',
        local: 'Times New Roman',
        metrics: 'timesNewRoman',
        platform: 'Windows / macOS / iOS',
      },
    ],
  },
  {
    file: 'src/fonts/public-sans-variable.woff2',
    label: 'Public Sans',
    fallbacks: [
      {
        family: 'Public Sans Fallback Roboto',
        local: 'Roboto',
        metrics: 'roboto',
        platform: 'Android',
      },
      {
        family: 'Public Sans Fallback Arial',
        local: 'Arial',
        metrics: 'arial',
        platform: 'Windows / macOS / iOS',
      },
    ],
  },
]

const pct = (n) => `${(n * 100).toFixed(2)}%`

const blocks = []
const rows = []

for (const stack of STACKS) {
  const webfont = await fromBuffer(readFileSync(stack.file))

  for (const fb of stack.fallbacks) {
    const system = (await import(`@capsizecss/metrics/${fb.metrics}`)).default

    const sizeAdjust =
      webfont.xWidthAvg / webfont.unitsPerEm / (system.xWidthAvg / system.unitsPerEm)
    const adjustedEmSquare = webfont.unitsPerEm * sizeAdjust

    const values = {
      sizeAdjust: pct(sizeAdjust),
      ascentOverride: pct(webfont.ascent / adjustedEmSquare),
      descentOverride: pct(Math.abs(webfont.descent) / adjustedEmSquare),
      lineGapOverride: pct(webfont.lineGap / adjustedEmSquare),
    }

    blocks.push(
      `/* ${stack.label} on ${fb.platform} — computed against ${system.familyName} */
@font-face {
  font-family: '${fb.family}';
  src: local('${fb.local}');
  size-adjust: ${values.sizeAdjust};
  ascent-override: ${values.ascentOverride};
  descent-override: ${values.descentOverride};
  line-gap-override: ${values.lineGapOverride};
}`,
    )

    rows.push({
      webfont: stack.label,
      against: system.familyName,
      platform: fb.platform,
      ...values,
    })
  }
}

const header = `/*
 * GENERATED by scripts/generate-font-fallbacks.mjs — do not edit by hand.
 *
 * Per-platform metric-matched fallbacks. next/font's adjustFontFallback is disabled
 * because the face it generates is src: local("Arial"), which does not exist on
 * Android — the device the perf budget is measured on — so its overrides silently
 * never apply there.
 *
 * Metrics read from the real subset woff2 by @capsizecss/unpack; system metrics from
 * @capsizecss/metrics. Re-run whenever a face is re-subset: these numbers describe
 * the binary, so they go stale the moment it changes.
 */
`

writeFileSync(OUT, `${header}\n${blocks.join('\n\n')}\n`, 'utf8')

const w = Math.max(...rows.map((r) => r.webfont.length))
console.log(
  `\n${'webfont'.padEnd(w)}  ${'against'.padEnd(16)}  ${'size-adj'.padStart(8)}  ${'ascent'.padStart(7)}  ${'descent'.padStart(7)}  ${'gap'.padStart(6)}  platform`,
)
console.log('-'.repeat(w + 70))
for (const r of rows) {
  console.log(
    `${r.webfont.padEnd(w)}  ${r.against.padEnd(16)}  ${r.sizeAdjust.padStart(8)}  ${r.ascentOverride.padStart(7)}  ${r.descentOverride.padStart(7)}  ${r.lineGapOverride.padStart(6)}  ${r.platform}`,
  )
}
console.log(`\nwrote ${OUT} — ${blocks.length} fallback faces\n`)
